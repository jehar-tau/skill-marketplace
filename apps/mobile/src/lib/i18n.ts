export function formatWhen(iso: string | Date, t: Dict): string {
  const d = new Date(iso);
  const now = new Date();
  const start = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const days = Math.round((start(d) - start(now)) / 86_400_000);
  const h = d.getHours();
  const time = `${h % 12 === 0 ? 12 : h % 12}:${String(d.getMinutes()).padStart(2, '0')} ${h < 12 ? 'AM' : 'PM'}`;
  const day = days === 0 ? t.today : days === 1 ? t.tomorrow : `${d.getDate()}/${d.getMonth() + 1}`;
  return `${day}, ${time}`;
}
